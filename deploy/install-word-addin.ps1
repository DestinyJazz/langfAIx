# Installs the Word add-in on this computer, for the current user only.
#
# No administrator rights, no shared folder, no visit to Word's Trust Center. It does two things:
#   1. copies the manifest (the file that tells Word the add-in's name and where its pages
#      are) to a fixed place on this computer
#   2. registers that file's location in the registry, where Word looks at startup
# The registry location and format follow Microsoft's own developer tool,
# office-addin-dev-settings (registerAddIn). Microsoft calls this sideloading and intends
# it for testing, not for formal distribution.
#
# Usage (in PowerShell):
#   powershell -ExecutionPolicy Bypass -File install-word-addin.ps1
#   powershell -ExecutionPolicy Bypass -File install-word-addin.ps1 -Manifest C:\path\langfaix-word-manifest.xml
#   powershell -ExecutionPolicy Bypass -File install-word-addin.ps1 -Uninstall
#
# Without -Manifest it looks for langfaix-word-manifest.xml next to this script, then in a
# build folder next to it. The manifest is generated by deploy/pack-word-addin.ps1 and
# contains the server address.
#
# Close all Word windows and reopen Word after installing.

param(
    [string]$Manifest = "",
    [switch]$Uninstall,
    # For tests only: another registry location and folder, so the real Word settings are untouched.
    [string]$RegistryKey = "HKCU:\Software\Microsoft\Office\16.0\WEF\Developer",
    [string]$InstallDir = ""
)

$ErrorActionPreference = "Stop"

function Fail($message) {
    Write-Host "INSTALL FAILED: $message" -ForegroundColor Red
    exit 1
}

if (-not $InstallDir) { $InstallDir = Join-Path $env:LOCALAPPDATA "langfAIx" }
# The manifest's fixed place on this computer. The registry holds this path, so the downloaded copy can be deleted afterwards.
$target = Join-Path $InstallDir "langfaix-word-manifest.xml"

# The value names under that registry key that point at our file.
function Find-OurEntries {
    if (-not (Test-Path $RegistryKey)) { return @() }
    $item = Get-Item -Path $RegistryKey
    $names = @()
    foreach ($name in $item.GetValueNames()) {
        if ([string]$item.GetValue($name) -ieq $target) { $names += $name }
    }
    return $names
}

function Warn-IfWordIsOpen {
    if (Get-Process -Name WINWORD -ErrorAction SilentlyContinue) {
        Write-Host "Word is open now. Close ALL Word windows and open Word again." -ForegroundColor Yellow
    } else {
        Write-Host "Now open Word."
    }
}

# ---------- Uninstall ----------

if ($Uninstall) {
    $names = @(Find-OurEntries)
    foreach ($name in $names) { Remove-ItemProperty -Path $RegistryKey -Name $name }
    if (Test-Path $target) { Remove-Item -Path $target -Force }
    if ($names.Count -eq 0) {
        Write-Host "langfAIx was not installed for this user. Nothing to remove."
    } else {
        Write-Host "Removed langfAIx from Word for this user."
        Warn-IfWordIsOpen
    }
    exit 0
}

# ---------- Find the manifest ----------

if ($Manifest) {
    if (-not (Test-Path $Manifest)) { Fail "there is no file '$Manifest'" }
    $source = (Resolve-Path $Manifest).Path
} else {
    $source = $null
    $candidates = @(
        (Join-Path $PSScriptRoot "langfaix-word-manifest.xml"),
        (Join-Path (Join-Path $PSScriptRoot "build") "langfaix-word-manifest.xml")
    )
    foreach ($candidate in $candidates) {
        if (Test-Path $candidate) { $source = $candidate; break }
    }
    if (-not $source) {
        Fail "langfaix-word-manifest.xml was not found next to this script. Put it in the same folder, or give its location with -Manifest."
    }
}

# ---------- Checks ----------
# With the slightest fault in the manifest Word silently does not show the add-in. So look at it here first.

$utf8 = New-Object System.Text.UTF8Encoding($false)
$text = [System.IO.File]::ReadAllText($source, $utf8)
# The template from the repo was passed: the addresses are still markers.
if ($text.Contains("{{")) { Fail "'$source' is the template, not a finished manifest. Create one with deploy/pack-word-addin.ps1 -ApiUrl https://your-server/api" }
try { $doc = [xml]$text } catch { Fail "'$source' is not valid XML: $($_.Exception.Message)" }
if (-not $doc.OfficeApp) { Fail "'$source' is not an Office add-in manifest" }

$id   = ([string]$doc.OfficeApp.Id).Trim()
$page = [string]$doc.OfficeApp.DefaultSettings.SourceLocation.DefaultValue
$guid = [System.Guid]::Empty
if (-not [System.Guid]::TryParse($id, [ref]$guid)) { Fail "the manifest has no valid Id" }
if ($page -notmatch '^https://') { Fail "the add-in page in the manifest is not an https address: '$page'" }

# ---------- Copy and register ----------

New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null
if ($source -ine $target) { Copy-Item -Path $source -Destination $target -Force }

# Create the key only if it does not exist. New-Item -Force on an existing key would wipe other add-ins' registrations.
if (-not (Test-Path $RegistryKey)) { New-Item -Path $RegistryKey -Force | Out-Null }
# If the same file was registered under another Id before, remove that first, or Word shows two.
foreach ($name in @(Find-OurEntries)) {
    if ($name -ine $id) { Remove-ItemProperty -Path $RegistryKey -Name $name }
}
# Value name: the add-in's Id. Value: the full path of the manifest (as Microsoft's tool writes it).
New-ItemProperty -Path $RegistryKey -Name $id -Value $target -PropertyType String -Force | Out-Null

Write-Host "Installed langfAIx for Word (this user only)."
Write-Host "  version : $($doc.OfficeApp.Version)"
Write-Host "  page    : $page"
Write-Host "  manifest: $target"
Write-Host ""
Warn-IfWordIsOpen
Write-Host "Look for the 'Check text' button on the Home tab."
Write-Host "If it is not there: Home > Add-ins > More Add-ins (or Advanced), and look for langfAIx under 'Developer Add-ins'."
Write-Host ""
Write-Host "To remove it later, run this script again with -Uninstall."
